<script lang="ts">
  // TeX rendered by KaTeX as MathML, which the webview draws natively: no KaTeX stylesheet
  // or fonts. KaTeX is large and most commits have no math, so it loads the first time it's
  // needed, with the source showing until then.
  import type Katex from 'katex'
  import { renderMath } from './math'

  let { tex, display = false }: { tex: string; display?: boolean } = $props()

  let katex = $state<typeof Katex | null>(null)
  $effect(() => {
    void import('katex').then((k) => (katex = k.default))
  })

  let html = $derived(katex ? renderMath(katex, tex, display) : undefined)
</script>

<!-- eslint-disable-next-line svelte/no-at-html-tags -- MathML generated by KaTeX with trust off -->
{#if html === undefined}<code>{tex}</code>{:else if display}<div class="math display">{@html html}</div>{:else}<span class="math">{@html html}</span>{/if}

<style>
  .display {
    margin: 10px 0;
    overflow-x: auto;
    text-align: center;
  }

  .math :global(math) {
    font-size: 1.1em;
  }

  /* KaTeX marks source it couldn't parse in its error colour; use ours. */
  .math :global([style*='color']) {
    color: var(--danger) !important;
  }
</style>
